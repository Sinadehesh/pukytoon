// Builds assets/library/sprites.js: every picture in assets/library/sprites/<set>/, with its size, a readable
// name and its hitbox outline. Run it after adding pictures:
//
//   node tools/build-library.mjs [path/to/shapes.js ...]
//
// Hitboxes are kept in assets/library/hitboxes.json. A shapes.js given on the command line (the format
// Happy-Fruit-merge's tools/make_shapes.py writes: "assets/<set>/<file>.png": [[x, y], ...]) adds or updates
// outlines for pictures in the library; pictures without one get a box hitbox in the game.
import fs from 'fs';
import path from 'path';

const root = path.resolve(import.meta.dirname, '..');
const lib = path.join(root, 'assets/library');
const hitboxFile = path.join(lib, 'hitboxes.json');
const hitboxes = fs.existsSync(hitboxFile) ? JSON.parse(fs.readFileSync(hitboxFile, 'utf8')) : {};

for (const shapesPath of process.argv.slice(2)) {
    const shapes = new Function(fs.readFileSync(shapesPath, 'utf8') + ';return SHAPES;')();
    for (const [key, outline] of Object.entries(shapes)) {
        const id = key.replace(/^assets\//, '').replace(/\.png$/, '');
        if (fs.existsSync(path.join(lib, 'sprites', id + '.png'))) hitboxes[id] = outline;
    }
}

// PNG width and height sit at bytes 16-23 of the file
function pngSize(file) {
    const b = fs.readFileSync(file);
    return [b.readUInt32BE(16), b.readUInt32BE(20)];
}

const name = file => file.replace(/^\d+_/, '').replace(/_/g, ' ').replace(/^./, c => c.toUpperCase());

const sprites = {};
for (const set of fs.readdirSync(path.join(lib, 'sprites')).sort()) {
    for (const file of fs.readdirSync(path.join(lib, 'sprites', set)).filter(f => f.endsWith('.png')).sort()) {
        const id = `${set}/${file.replace(/\.png$/, '')}`;
        const [w, h] = pngSize(path.join(lib, 'sprites', set, file));
        sprites[id] = { url: `assets/library/sprites/${id}.png`, w, h, name: name(file.replace(/\.png$/, '')) };
        if (hitboxes[id]) sprites[id].hitbox = hitboxes[id];
    }
}

fs.writeFileSync(hitboxFile, JSON.stringify(hitboxes) + '\n');
fs.writeFileSync(path.join(lib, 'sprites.js'),
    '// Generated by tools/build-library.mjs from assets/library/sprites/. Do not edit by hand.\n' +
    '// id -> picture: url (from the site root), size in px, name, and a hitbox outline in picture pixels.\n' +
    `export const SPRITES = ${JSON.stringify(sprites, null, 0).replace(/\},"/g, '},\n"')};\n`);
const withBox = Object.values(sprites).filter(s => s.hitbox).length;
console.log(`library: ${Object.keys(sprites).length} pictures, ${withBox} with traced hitboxes`);
